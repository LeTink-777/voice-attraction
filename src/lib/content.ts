export interface VoiceResult {
  score: number;
  band: 'high' | 'medium' | 'low';
  bandLabel: string;
  bandText: string;
  strengths: Trait[];
  weaknesses: Trait[];
  analysis: string;
  goodPhrases: string;
  badPhrases: string;
  script: string;
  dateTips: string;
  plan30: string;
}

export function parseAnswers(value: string | undefined): number[] | null {
  if (!value) return null;
  try {
    const parsed = JSON.parse(value);
    if (!Array.isArray(parsed) || parsed.length !== QUESTIONS.length) return null;
    return parsed.map((n) => Number(n) || 0);
  } catch {
    return null;
  }
}

export function computeResult(answers: number[]): VoiceResult {
  const scores = QUESTIONS.map((q, i) => ({
    trait: q.trait,
    value: q.options[answers[i]]?.score ?? 0,
  }));

  const total = scores.reduce((sum, s) => sum + s.value, 0);
  const score = Math.round((total / (QUESTIONS.length * 10)) * 100);

  const sorted = [...scores].sort((a, b) => b.value - a.value);
  const strengths = sorted.slice(0, 3).map((s) => s.trait);
  const weaknesses = sorted.slice(-2).map((s) => s.trait).reverse();

  const band = score >= 75 ? 'high' : score >= 40 ? 'medium' : 'low';

  const bandLabel =
    band === 'high'
      ? 'Высокое притяжение'
      : band === 'medium'
        ? 'Среднее притяжение'
        : 'Притяжение заблокировано';

  const bandText =
    band === 'high'
      ? `${score} баллов из 100 — высокое притяжение. Вы инстинктивно делаете то, что создаёт связь с людьми: слушаете, замечаете, не перетягиваете внимание. Ваша задача не «прокачаться», а перестать терять это в стрессе и спешке.`
      : band === 'medium'
        ? `${score} баллов из 100 — среднее притяжение. База у вас рабочая: вы не отталкиваете людей, но и не создаёте того эффекта, после которого хотят встретиться снова. Разница между вами и высоким баллом — три-четыре конкретные привычки, а не характер.`
        : `${score} баллов из 100 — притяжение заблокировано. Дело почти никогда не в том, что вы «неинтересный». Дело в наборе привычек, которые считываются как незаинтересованность: перебивание, разговор о себе, отвлечение. Это чинится быстрее, чем кажется, потому что менять надо поведение, а не себя.`;

  const analysis =
    band === 'high'
      ? 'Ваш стиль общения строится на внимании. Вы даёте собеседнику пространство и возвращаете ему то, что он сказал, — это создаёт ощущение редкой безопасности. Слабое место людей с высоким баллом одно: они расходуют этот ресурс на всех подряд и выгорают. Начните выбирать, кому давать полное присутствие, а с кем общаться поверхностно и без вины.'
      : band === 'medium'
        ? 'Ваш стиль общения неровный: с одними людьми вы включены полностью, с другими работаете на автопилоте. Обычно граница проходит по тому, насколько вам интересен человек, и это заметно снаружи. Самый быстрый рост даст не новая техника, а ровность: одинаковое качество внимания вне зависимости от того, кто перед вами.'
        : 'Ваш стиль общения сейчас центрирован на себе — не из эгоизма, а чаще из тревоги: когда человек волнуется, он заполняет пространство словами. Начните с одного: в следующем разговоре не рассказывайте о себе, пока не зададите три вопроса. Этот единственный приём обычно поднимает балл на 15–20 пунктов за месяц.';

  const goodPhrases =
    '«Расскажи подробнее — мне правда интересно». Работает потому, что снимает с собеседника сомнение, стоит ли продолжать.\n\n«Я запомнил, ты говорил про... чем закончилось?» Возврат к детали через время — самый сильный сигнал внимания из существующих.\n\n«Что ты сам об этом думаешь?» Передаёт человеку право быть экспертом в своей жизни, и он это запоминает.';

  const badPhrases =
    '«У меня было то же самое, вот у меня...» Перехват темы на себя. Собеседник замолкает и больше не открывается.\n\n«Да ладно, это ерунда, не переживай». Обесценивание. Даже с добрым намерением читается как «мне неинтересно твоё состояние».\n\n«Ну я же говорил». Ставит вас выше собеседника и закрывает разговор навсегда.';

  const script =
    'Скрипт для сложного разговора. Шаг 1 — назначьте время и место: «Есть тема, которую мне важно обсудить. Тебе удобно сегодня в семь?» Шаг 2 — начните с факта, а не с оценки: «За последние две недели мы трижды переносили встречу». Шаг 3 — скажите о своём состоянии, а не о его вине: «Мне из-за этого тревожно». Шаг 4 — сформулируйте просьбу, а не претензию: «Мне важно, чтобы мы договаривались заранее». Шаг 5 — замолчите и дайте ответить, не заполняя паузу.';

  const dateTips =
    'Первое свидание. Первые десять минут — только вопросы, никаких рассказов о себе: это сразу отличает вас от 90% людей. Не обсуждайте бывших, работу в деталях и жалобы на что угодно. Уточняйте детали в его ответах вместо смены темы — это создаёт ощущение глубины. Телефон уберите со стола совсем. Заканчивайте первым и на подъёме: встреча, законченная чуть раньше, чем хотелось, запоминается лучше затянувшейся. И скажите прямо, если понравилось, — недосказанность на первом свидании чаще читается как безразличие.';

  const plan30 =
    'Дни 1–7: правило трёх вопросов. В каждом разговоре задайте три вопроса, прежде чем расскажете о себе.\n\nДни 8–14: пауза. После того как собеседник замолчал, считайте до трёх. Главное почти всегда говорится после паузы.\n\nДни 15–21: память. После каждого важного разговора записывайте две детали и возвращайтесь к ним при следующей встрече.\n\nДни 22–30: признание. Один конкретный искренний комплимент в день — не «ты молодец», а «мне понравилось, как ты решил вопрос с подрядчиком».\n\nВ конце месяца пройдите тест заново: типичный рост — 12–20 баллов.';

  return {
    score,
    band,
    bandLabel,
    bandText,
    strengths,
    weaknesses,
    analysis,
    goodPhrases,
    badPhrases,
    script,
    dateTips,
    plan30,
  };
}

export function pdfTitle(userData: UserData): string {
  const answers = parseAnswers(userData.answers);
  if (!answers) return SITE.name;
  const r = computeResult(answers);
  return `Притяжение в общении — ${r.score} из 100`;
}

export function buildSections(userData: UserData, plan: PlanId): Section[] {
  const answers = parseAnswers(userData.answers);

  if (!answers) {
    return [
      {
        title: 'Данные не распознаны',
        content:
          'Не удалось прочитать ответы теста. Вернитесь на сайт и пройдите тест заново — это займёт две минуты.',
      },
    ];
  }

  const r = computeResult(answers);
  const sections: Section[] = [];

  sections.push({ title: 'Твой уровень притяжения в общении', content: r.bandText });

  sections.push({
    title: 'Твои сильные стороны',
    content: r.strengths
      .map((t) => `${TRAIT_NAMES[t]}. ${STRENGTH_TEXT[t]}`)
      .join('\n\n'),
  });

  sections.push({
    title: 'Зоны роста',
    content: r.weaknesses
      .map((t) => `${TRAIT_NAMES[t]}. ${WEAKNESS_TEXT[t]}`)
      .join('\n\n'),
  });

  if (plan === 'full' || plan === 'premium') {
    sections.push({ title: 'Полный анализ стиля общения', content: r.analysis });
    sections.push({ title: '3 фразы, которые усиливают притяжение', content: r.goodPhrases });
    sections.push({ title: '3 фразы, которые его убивают', content: r.badPhrases });
    sections.push({ title: 'Скрипт для сложного разговора', content: r.script });
  }

  if (plan === 'premium') {
    sections.push({ title: 'Как вести себя на первом свидании', content: r.dateTips });
    sections.push({ title: '30-дневный план прокачки речи', content: r.plan30 });
    sections.push({
      title: 'Аудиоразбор',
      content:
        'Аудиоверсия разбора записывается индивидуально и приходит отдельным письмом в течение 6 часов. Длительность — около 13 минут.',
    });
  }

  sections.push({
    title: 'О документе',
    content: `Тариф: ${PLAN_LABELS[plan]}. Материал носит развлекательный и познавательный характер и не является психологической консультацией.`,
  });

  return sections;
}
